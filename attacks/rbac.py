"""OWASP API5:2023 (BFLA / RBAC) reproducible attack script for APIShield.

Performs controlled unauthorized administrative function access attempts against synthetic data.
Strictly validates scheme, host, and port before making any network requests.
Correlates the exact security event generated by this attack attempt.
Never prints or logs passwords, tokens, or Authorization headers.
"""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
from typing import Any, Optional
from urllib.parse import urlparse
import httpx

ALLOWED_SCHEMES = {"http"}
ALLOWED_HOSTS = {"127.0.0.1", "localhost", "api"}
ALLOWED_PORTS = {8000}


def validate_target_url(target_url: str) -> str:
    """Validate target URL against hardcoded local security allowlist.

    Must be called before making any network requests.
    Enforces scheme, host, port, and URL hygiene. Raises ValueError if invalid.
    """
    if not target_url or not isinstance(target_url, str):
        raise ValueError("Target URL must be a non-empty string.")

    parsed = urlparse(target_url.strip())

    if parsed.scheme.lower() not in ALLOWED_SCHEMES:
        raise ValueError(
            f"Disallowed scheme '{parsed.scheme}'. Scheme must be strictly 'http'."
        )

    hostname = (parsed.hostname or "").lower()
    if not hostname or hostname not in ALLOWED_HOSTS:
        raise ValueError(
            f"Disallowed target host '{hostname}'. Host must be one of: {sorted(ALLOWED_HOSTS)}."
        )

    port = parsed.port
    if port is None or port not in ALLOWED_PORTS:
        raise ValueError(
            f"Disallowed or missing port '{port}'. Port must be strictly: {sorted(ALLOWED_PORTS)}."
        )

    if parsed.username or parsed.password:
        raise ValueError("Embedded credentials in target URL are prohibited.")

    if parsed.query or parsed.fragment:
        raise ValueError("Target URL must not contain query strings or fragments.")

    # Return normalized base URL without trailing slash
    return f"{parsed.scheme}://{hostname}:{port}"


def run_rbac_attack(
    target_url: str,
    results_path: Optional[Path] = None,
    client: Optional[httpx.Client] = None,
) -> dict[str, Any]:
    """Execute the controlled BFLA / RBAC attack experiment.

    Steps:
    1. Validate scheme, hostname, and port before any network activity.
    2. Admin baseline check: capture latest event ID before the attack to ensure
       exact correlation of the event emitted by this attack attempt.
    3. Authenticate synthetic non-admin user 'alice' (never logging credentials/token).
    4. Attempt unauthorized read of administrative events (/admin/events).
    5. Authenticate as 'admin' to verify the exact correlated security event.
    6. Save structured results to docs/results/rbac_results.json.
    """
    # Step 1: Pre-flight validation
    base_url = validate_target_url(target_url)

    # Use provided client (e.g. for testing) or instantiate a new one
    close_client = False
    if client is None:
        client = httpx.Client(timeout=10.0)
        close_client = True

    try:
        # Step 2: Establish baseline as admin before attack
        admin_login = client.post(
            f"{base_url}/auth/login",
            json={"username": "admin", "password": "AdminSyntheticPass123!"},
        )
        if admin_login.status_code != 200:
            raise RuntimeError(
                f"Admin baseline authentication failed: HTTP {admin_login.status_code}"
            )

        admin_token = admin_login.json().get("access_token")
        if not admin_token:
            raise RuntimeError("Admin login response missing access_token.")
        admin_headers = {"Authorization": f"Bearer {admin_token}"}

        # Query highest event ID before attack for correlation
        latest_id_before = 0
        events_baseline = client.get(
            f"{base_url}/admin/events?limit=1",
            headers=admin_headers,
        )
        if events_baseline.status_code == 200:
            events_list = events_baseline.json().get("events", [])
            if events_list:
                latest_id_before = events_list[0].get("id", 0)

        # Inspect current rbac defense toggle state
        defense_active = None
        def_res = client.get(f"{base_url}/admin/defenses", headers=admin_headers)
        if def_res.status_code == 200:
            defense_active = def_res.json().get("defenses", {}).get("rbac", False)

        # Step 3: Authenticate synthetic attacker 'alice'
        login_res = client.post(
            f"{base_url}/auth/login",
            json={"username": "alice", "password": "AliceSyntheticPass123!"},
        )
        if login_res.status_code != 200:
            raise RuntimeError(
                f"Authentication failed for synthetic attacker 'alice': HTTP {login_res.status_code}"
            )

        alice_token = login_res.json().get("access_token")
        alice_id = login_res.json().get("user", {}).get("id")
        if not alice_token:
            raise RuntimeError("Alice login response did not contain an access_token.")

        # Step 4: Attempt unauthorized administrative access to /admin/events
        headers_alice = {"Authorization": f"Bearer {alice_token}"}
        target_endpoint = "/admin/events"
        attack_res = client.get(
            f"{base_url}{target_endpoint}",
            headers=headers_alice,
        )

        status_code = attack_res.status_code
        attack_success = status_code == 200 and isinstance(
            attack_res.json().get("events"), list
        )
        blocked = status_code == 403

        # Step 5: Verify exact correlated security event via Admin API
        detection_verified = False
        matched_event_id: Optional[int] = None
        try:
            events_post = client.get(
                f"{base_url}/admin/events?limit=20",
                headers=admin_headers,
            )
            if events_post.status_code == 200:
                post_events = events_post.json().get("events", [])
                expected_action = "blocked" if blocked else "detected"
                for ev in post_events:
                    # Match only new events strictly created during this attack run
                    if (
                        ev.get("id") > latest_id_before
                        and ev.get("owasp_category") == "API5:2023"
                        and ev.get("rule_name") == "bfla_unauthorized_function_access"
                        and ev.get("endpoint") == target_endpoint
                        and ev.get("user_id") == alice_id
                        and ev.get("action") == expected_action
                    ):
                        detection_verified = True
                        matched_event_id = ev.get("id")
                        break
        except Exception:
            detection_verified = False

        # Step 6: Construct structured outcome
        if attack_success:
            outcome = (
                "vulnerability_exploited"
                if detection_verified
                else "unverified_detection"
            )
        elif blocked:
            outcome = (
                "attack_blocked"
                if detection_verified
                else "unverified_detection"
            )
        else:
            outcome = "unexpected"
        result = {
            "experiment": "OWASP API5:2023 BFLA/RBAC",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "target": base_url,
            "attacker": "alice",
            "target_endpoint": target_endpoint,
            "status_code": status_code,
            "detection_verified": detection_verified,
            "matched_event_id": matched_event_id,
            "blocked": blocked,
            "attack_success": attack_success,
            "defense_active": defense_active,
            "outcome": outcome,
        }

        # Step 7: Persist results
        if results_path is not False:
            if results_path is None:
                results_path = (
                    Path(__file__).resolve().parent.parent
                    / "docs"
                    / "results"
                    / "rbac_results.json"
                )

            results_path.parent.mkdir(parents=True, exist_ok=True)
            results_path.write_text(json.dumps(result, indent=2), encoding="utf-8")

        return result
    finally:
        if close_client:
            client.close()


def main(
    target_url: Optional[str] = None,
    results_path: Optional[Path] = None,
    client: Optional[httpx.Client] = None,
    raise_on_failure: bool = False,
) -> None:
    """CLI entry point for running the BFLA / RBAC attack experiment.

    Runs two sequential attack passes with an admin-managed defense toggle:
      Run 1 — rbac defense OFF (vulnerable mode, outcome: vulnerability_exploited)
      Run 2 — rbac defense ON  (mitigated mode, outcome: attack_blocked)
    Restores the original defense state after both runs.
    Never prints or persists tokens or credentials.
    Writes combined results to docs/results/rbac_results.json only upon full verification.
    """
    if target_url is None:
        parser = argparse.ArgumentParser(
            description="APIShield OWASP API5:2023 BFLA/RBAC Attack Experiment Script"
        )
        parser.add_argument(
            "--target",
            default="http://127.0.0.1:8000",
            help="Target base URL (default: http://127.0.0.1:8000)",
        )
        args = parser.parse_args()
        target_to_use = args.target
    else:
        target_to_use = target_url

    try:
        # Pre-flight check before anything else
        validate_target_url(target_to_use)
    except ValueError as exc:
        print(f"[REJECTED] Target validation failed: {exc}", file=sys.stderr)
        if raise_on_failure:
            raise
        sys.exit(1)

    print("==================================================")
    print(" APIShield BFLA / RBAC Experiment Execution")
    print(f" Target: {target_to_use}")
    print("==================================================")

    base_url = target_to_use.rstrip("/")
    if results_path is None:
        target_results_path = (
            Path(__file__).resolve().parent.parent
            / "docs"
            / "results"
            / "rbac_results.json"
        )
    else:
        target_results_path = results_path

    close_client = False
    if client is None:
        client = httpx.Client(timeout=10.0)
        close_client = True

    try:
        # Authenticate as admin once to manage the defense toggle.
        # Token is kept in memory only — never printed or persisted.
        admin_login = client.post(
            f"{base_url}/auth/login",
            json={"username": "admin", "password": "AdminSyntheticPass123!"},
        )
        if admin_login.status_code != 200:
            raise RuntimeError(
                f"Admin authentication failed: HTTP {admin_login.status_code}"
            )
        admin_token = admin_login.json().get("access_token")
        if not admin_token:
            raise RuntimeError("Admin login response missing access_token.")
        admin_headers = {"Authorization": f"Bearer {admin_token}"}

        # Capture original defense state to restore after experiment
        def_res = client.get(f"{base_url}/admin/defenses", headers=admin_headers)
        if def_res.status_code != 200:
            raise RuntimeError(
                f"Failed to fetch initial defense states: HTTP {def_res.status_code}"
            )
        defenses_map = def_res.json().get("defenses")
        if not isinstance(defenses_map, dict) or "rbac" not in defenses_map:
            raise RuntimeError(
                "Invalid defense state response: missing 'rbac' defense toggle."
            )
        original_rbac = defenses_map["rbac"]

        try:
            # --- Run 1: Defense OFF (vulnerable mode) ---
            print("\n[Run 1] Setting rbac defense OFF (vulnerable mode)...")
            patch_off = client.patch(
                f"{base_url}/admin/defenses",
                json={"rbac": False},
                headers=admin_headers,
            )
            if patch_off.status_code != 200 or not patch_off.json().get("defenses", {}).get("rbac") is False:
                raise RuntimeError(
                    f"Failed to set rbac defense toggle to OFF: HTTP {patch_off.status_code}"
                )

            result_off = run_rbac_attack(
                target_url=target_to_use,
                results_path=False,
                client=client,
            )
            if (
                result_off.get("status_code") != 200
                or not result_off.get("attack_success")
                or not result_off.get("detection_verified")
                or result_off.get("defense_active") is not False
                or result_off.get("outcome") != "vulnerability_exploited"
            ):
                raise RuntimeError(
                    "Run 1 (defense OFF) failed verification or did not observe rbac=False."
                )

            # --- Run 2: Defense ON (mitigated mode) ---
            print("\n[Run 2] Setting rbac defense ON (mitigated mode)...")
            patch_on = client.patch(
                f"{base_url}/admin/defenses",
                json={"rbac": True},
                headers=admin_headers,
            )
            if patch_on.status_code != 200 or not patch_on.json().get("defenses", {}).get("rbac") is True:
                raise RuntimeError(
                    f"Failed to set rbac defense toggle to ON: HTTP {patch_on.status_code}"
                )

            result_on = run_rbac_attack(
                target_url=target_to_use,
                results_path=False,
                client=client,
            )
            if (
                result_on.get("status_code") != 403
                or not result_on.get("blocked")
                or not result_on.get("detection_verified")
                or result_on.get("defense_active") is not True
                or result_on.get("outcome") != "attack_blocked"
            ):
                raise RuntimeError(
                    "Run 2 (defense ON) failed verification or did not observe rbac=True."
                )
        finally:
            # Always attempt to restore original defense state on every exit path
            try:
                restore_res = client.patch(
                    f"{base_url}/admin/defenses",
                    json={"rbac": original_rbac},
                    headers=admin_headers,
                )
                restored_rbac = (
                    restore_res.json().get("defenses", {}).get("rbac")
                    if restore_res.status_code == 200
                    else None
                )
                if restore_res.status_code != 200 or restored_rbac != original_rbac:
                    print(
                        f"[WARNING] Failed to restore original rbac defense state (HTTP {restore_res.status_code}, "
                        f"rbac={restored_rbac}, expected={original_rbac}). "
                        "The server's RBAC defense state may be unresolved.",
                        file=sys.stderr,
                    )
            except Exception as restore_exc:
                print(
                    f"[WARNING] Exception during rbac defense state restoration: {restore_exc}. "
                    "The server's RBAC defense state may be unresolved.",
                    file=sys.stderr,
                )

        # Write combined dual-run results (no tokens or credentials stored)
        combined = {
            "experiment": "OWASP API5:2023 BFLA/RBAC",
            "timestamp": result_on["timestamp"],
            "target": result_on["target"],
            "attacker": "alice",
            "target_endpoint": "/admin/events",
            "vulnerable_run": {
                "defense_active": result_off["defense_active"],
                "status_code": result_off["status_code"],
                "attack_success": result_off["attack_success"],
                "blocked": result_off["blocked"],
                "detection_verified": result_off["detection_verified"],
                "matched_event_id": result_off["matched_event_id"],
                "outcome": result_off["outcome"],
            },
            "defended_run": {
                "defense_active": result_on["defense_active"],
                "status_code": result_on["status_code"],
                "attack_success": result_on["attack_success"],
                "blocked": result_on["blocked"],
                "detection_verified": result_on["detection_verified"],
                "matched_event_id": result_on["matched_event_id"],
                "outcome": result_on["outcome"],
            },
        }
        target_results_path.parent.mkdir(parents=True, exist_ok=True)
        target_results_path.write_text(json.dumps(combined, indent=2), encoding="utf-8")

        print("\n--- Experiment Summary ---")
        print(
            f" [Vulnerable] HTTP {result_off['status_code']} | "
            f"{result_off['outcome']} | detection_verified={result_off['detection_verified']}"
        )
        print(
            f" [Defended]   HTTP {result_on['status_code']} | "
            f"{result_on['outcome']} | detection_verified={result_on['detection_verified']}"
        )
        print(f" Results written to: {target_results_path}")
        print("==================================================")
    except Exception as exc:
        print(f"[ERROR] Experiment failed: {exc}", file=sys.stderr)
        if raise_on_failure:
            raise
        sys.exit(1)
    finally:
        if close_client:
            client.close()


if __name__ == "__main__":
    main()
