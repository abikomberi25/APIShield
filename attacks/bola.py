"""OWASP API1:2023 (BOLA) reproducible attack script for APIShield.

Performs controlled cross-user access attempts against seeded synthetic data.
Strictly validates scheme, host, and port before making any network requests.
Correlates the exact security event generated by this attack attempt.
Never prints or logs passwords, tokens, or Authorization headers.
"""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
from typing import Any, Optional, Union
from urllib.parse import urlparse
import httpx

ALLOWED_SCHEMES = {"http"}
ALLOWED_HOSTS = {"127.0.0.1", "localhost", "api"}
ALLOWED_PORTS = {8000}


def validate_target_url(target_url: str) -> str:
    """Validate target URL against hardcoded local security allowlist.

    Must be called before making any network requests.
    Enforces scheme, host, port, and URL hygiene. Raises ValueError if invalid.
    """
    if not target_url or not isinstance(target_url, str):
        raise ValueError("Target URL must be a non-empty string.")

    parsed = urlparse(target_url.strip())

    if parsed.scheme.lower() not in ALLOWED_SCHEMES:
        raise ValueError(
            f"Disallowed scheme '{parsed.scheme}'. Scheme must be strictly 'http'."
        )

    hostname = (parsed.hostname or "").lower()
    if not hostname or hostname not in ALLOWED_HOSTS:
        raise ValueError(
            f"Disallowed target host '{hostname}'. Host must be one of: {sorted(ALLOWED_HOSTS)}."
        )

    port = parsed.port
    if port is None or port not in ALLOWED_PORTS:
        raise ValueError(
            f"Disallowed or missing port '{port}'. Port must be strictly: {sorted(ALLOWED_PORTS)}."
        )

    if parsed.username or parsed.password:
        raise ValueError("Embedded credentials in target URL are prohibited.")

    if parsed.query or parsed.fragment:
        raise ValueError("Target URL must not contain query strings or fragments.")

    # Return normalized base URL without trailing slash
    return f"{parsed.scheme}://{hostname}:{port}"


def run_bola_attack(
    target_url: str,
    results_path: Optional[Union[Path, bool]] = None,
    client: Optional[httpx.Client] = None,
) -> dict[str, Any]:
    """Execute a single controlled BOLA attack experiment run.

    Steps:
    1. Validate scheme, hostname, and port before any network activity.
    2. Admin baseline check: capture latest event ID before the attack to ensure
       exact correlation of the event emitted by this attack attempt.
    3. Authenticate synthetic non-admin user 'alice' (never logging credentials/token).
    4. Attempt unauthorized cross-user read of Bob's item at /items/3.
    5. Authenticate as 'admin' to verify the exact correlated security event.
    6. Save structured results only for verified outcomes, unless results_path=False.
    """
    # Step 1: Pre-flight validation
    base_url = validate_target_url(target_url)

    # Use provided client (e.g. for testing) or instantiate a new one
    close_client = False
    if client is None:
        client = httpx.Client(timeout=10.0)
        close_client = True

    try:
        # Step 2: Establish admin baseline before attack
        admin_login = client.post(
            f"{base_url}/auth/login",
            json={"username": "admin", "password": "AdminSyntheticPass123!"},
        )
        if admin_login.status_code != 200:
            raise RuntimeError(
                f"Admin baseline authentication failed: HTTP {admin_login.status_code}"
            )

        admin_token = admin_login.json().get("access_token")
        if not admin_token:
            raise RuntimeError("Admin login response missing access_token.")
        admin_headers = {"Authorization": f"Bearer {admin_token}"}

        # Query highest event ID before attack for exact post-attack correlation
        latest_id_before = 0
        events_baseline = client.get(
            f"{base_url}/admin/events?limit=1",
            headers=admin_headers,
        )
        if events_baseline.status_code == 200:
            events_list = events_baseline.json().get("events", [])
            if events_list:
                latest_id_before = events_list[0].get("id", 0)

        # Inspect current bola defense toggle state
        defense_active = None
        def_res = client.get(f"{base_url}/admin/defenses", headers=admin_headers)
        if def_res.status_code == 200:
            defense_active = def_res.json().get("defenses", {}).get("bola", False)

        # Step 3: Authenticate synthetic attacker 'alice'
        login_res = client.post(
            f"{base_url}/auth/login",
            json={"username": "alice", "password": "AliceSyntheticPass123!"},
        )
        if login_res.status_code != 200:
            raise RuntimeError(
                f"Authentication failed for synthetic attacker 'alice': HTTP {login_res.status_code}"
            )

        alice_token = login_res.json().get("access_token")
        alice_id = login_res.json().get("user", {}).get("id")
        if not alice_token:
            raise RuntimeError("Alice login response did not contain an access_token.")

        # Step 4: Attempt cross-user read on Bob's Item 3
        headers_alice = {"Authorization": f"Bearer {alice_token}"}
        target_item_id = 3
        attack_res = client.get(
            f"{base_url}/items/{target_item_id}",
            headers=headers_alice,
        )

        status_code = attack_res.status_code
        attack_success = status_code == 200 and attack_res.json().get("id") == target_item_id
        blocked = status_code == 403

        # Step 5: Verify exact correlated security event via Admin API
        detection_verified = False
        matched_event_id: Optional[int] = None
        if attack_success or blocked:
            expected_action = "blocked" if blocked else "detected"
            try:
                events_post = client.get(
                    f"{base_url}/admin/events?limit=20",
                    headers=admin_headers,
                )
                if events_post.status_code == 200:
                    post_events = events_post.json().get("events", [])
                    for ev in post_events:
                        if (
                            ev.get("id") > latest_id_before
                            and ev.get("owasp_category") == "API1:2023"
                            and ev.get("rule_name") == "bola_cross_tenant_access"
                            and ev.get("object_id") == str(target_item_id)
                            and ev.get("action") == expected_action
                            and (alice_id is None or ev.get("user_id") == alice_id)
                        ):
                            detection_verified = True
                            matched_event_id = ev.get("id")
                            break
            except Exception:
                detection_verified = False

        # Step 6: Construct structured outcome
        if attack_success:
            outcome = (
                "vulnerability_exploited"
                if detection_verified
                else "unverified_detection"
            )
        elif blocked:
            outcome = (
                "attack_blocked"
                if detection_verified
                else "unverified_detection"
            )
        else:
            outcome = "unexpected"

        # Explicit verification_passed flag for programmatic consumption
        verification_passed = detection_verified and outcome in (
            "vulnerability_exploited",
            "attack_blocked",
        )

        result = {
            "experiment": "OWASP API1:2023 BOLA",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "target": base_url,
            "attacker": "alice",
            "target_object_id": target_item_id,
            "status_code": status_code,
            "detection_verified": detection_verified,
            "matched_event_id": matched_event_id,
            "blocked": blocked,
            "attack_success": attack_success,
            "defense_active": defense_active,
            "outcome": outcome,
            "verification_passed": verification_passed,
        }

        # Persist results only for verified outcomes and when not explicitly suppressed
        if results_path is not False and outcome in ("vulnerability_exploited", "attack_blocked"):
            if results_path is None:
                results_path = (
                    Path(__file__).resolve().parent.parent
                    / "docs"
                    / "results"
                    / "bola_results.json"
                )

            results_path.parent.mkdir(parents=True, exist_ok=True)
            results_path.write_text(json.dumps(result, indent=2), encoding="utf-8")

        return result
    finally:
        if close_client:
            client.close()


def main(
    target_url: Optional[str] = None,
    results_path: Optional[Union[Path, bool]] = None,
    client: Optional[httpx.Client] = None,
    raise_on_failure: bool = False,
) -> None:
    """CLI entry point for running the BOLA dual-run experiment.

    Runs two sequential attack passes with an admin-managed bola defense toggle:
      Run 1 — bola defense OFF (vulnerable mode, outcome: vulnerability_exploited)
      Run 2 — bola defense ON  (defended mode, outcome: attack_blocked)
    Restores the original defense state after both runs in a finally block.
    Requires lab mode to be active; aborts if it is not.
    Never prints or persists tokens, credentials, or Authorization headers.
    Writes combined results to docs/results/bola_results.json only upon
    full verification of both runs and successful state restoration.
    """
    if target_url is None:
        parser = argparse.ArgumentParser(
            description="APIShield OWASP API1:2023 BOLA Attack Experiment Script"
        )
        parser.add_argument(
            "--target",
            default="http://127.0.0.1:8000",
            help="Target base URL (default: http://127.0.0.1:8000)",
        )
        args = parser.parse_args()
        target_to_use = args.target
    else:
        target_to_use = target_url

    try:
        # Pre-flight check before any network activity
        validate_target_url(target_to_use)
    except ValueError as exc:
        print(f"[REJECTED] Target validation failed: {exc}", file=sys.stderr)
        if raise_on_failure:
            raise
        sys.exit(1)

    print("==================================================")
    print(" APIShield BOLA Experiment Execution")
    print(f" Target: {target_to_use}")
    print("==================================================")

    base_url = target_to_use.rstrip("/")
    if results_path is None:
        target_results_path: Union[Path, bool] = (
            Path(__file__).resolve().parent.parent
            / "docs"
            / "results"
            / "bola_results.json"
        )
    else:
        target_results_path = results_path

    close_client = False
    if client is None:
        client = httpx.Client(timeout=10.0)
        close_client = True

    try:
        # Authenticate as admin once to manage the defense toggle.
        # Token is kept in memory only — never printed or persisted.
        admin_login = client.post(
            f"{base_url}/auth/login",
            json={"username": "admin", "password": "AdminSyntheticPass123!"},
        )
        if admin_login.status_code != 200:
            raise RuntimeError(
                f"Admin authentication failed: HTTP {admin_login.status_code}"
            )
        admin_token = admin_login.json().get("access_token")
        if not admin_token:
            raise RuntimeError("Admin login response missing access_token.")
        admin_headers = {"Authorization": f"Bearer {admin_token}"}

        # Verify lab mode is enabled before any experiment activity
        lab_res = client.get(f"{base_url}/admin/lab-mode", headers=admin_headers)
        if lab_res.status_code != 200:
            raise RuntimeError(
                f"Failed to check lab mode status: HTTP {lab_res.status_code}"
            )
        if not lab_res.json().get("lab_mode", False):
            raise RuntimeError(
                "Lab mode is not enabled. Start the server with APISHIELD_LAB_MODE=true "
                "before running the BOLA experiment. Experiment aborted."
            )

        # Capture original defense state to restore after experiment
        def_res = client.get(f"{base_url}/admin/defenses", headers=admin_headers)
        if def_res.status_code != 200:
            raise RuntimeError(
                f"Failed to fetch initial defense states: HTTP {def_res.status_code}"
            )
        defenses_map = def_res.json().get("defenses")
        if not isinstance(defenses_map, dict) or "bola" not in defenses_map:
            raise RuntimeError(
                "Invalid defense state response: missing 'bola' defense toggle."
            )
        original_bola = defenses_map["bola"]

        restoration_succeeded = False

        try:
            # --- Run 1: Defense OFF (vulnerable mode) ---
            print("\n[Run 1] Setting bola defense OFF (vulnerable mode)...")
            patch_off = client.patch(
                f"{base_url}/admin/defenses",
                json={"bola": False},
                headers=admin_headers,
            )
            if (
                patch_off.status_code != 200
                or patch_off.json().get("defenses", {}).get("bola") is not False
            ):
                raise RuntimeError(
                    f"Failed to set bola defense toggle to OFF: "
                    f"HTTP {patch_off.status_code}"
                )

            result_off = run_bola_attack(
                target_url=target_to_use,
                results_path=False,
                client=client,
            )
            if not result_off.get("verification_passed"):
                raise RuntimeError(
                    "Run 1 (bola OFF) failed verification: expected "
                    f"vulnerability_exploited with verification_passed=True, "
                    f"got outcome={result_off.get('outcome')!r}, "
                    f"verification_passed={result_off.get('verification_passed')!r}."
                )

            # --- Run 2: Defense ON (defended mode) ---
            print("\n[Run 2] Setting bola defense ON (defended mode)...")
            patch_on = client.patch(
                f"{base_url}/admin/defenses",
                json={"bola": True},
                headers=admin_headers,
            )
            if (
                patch_on.status_code != 200
                or patch_on.json().get("defenses", {}).get("bola") is not True
            ):
                raise RuntimeError(
                    f"Failed to set bola defense toggle to ON: "
                    f"HTTP {patch_on.status_code}"
                )

            result_on = run_bola_attack(
                target_url=target_to_use,
                results_path=False,
                client=client,
            )
            if not result_on.get("verification_passed"):
                raise RuntimeError(
                    "Run 2 (bola ON) failed verification: expected "
                    f"attack_blocked with verification_passed=True, "
                    f"got outcome={result_on.get('outcome')!r}, "
                    f"verification_passed={result_on.get('verification_passed')!r}."
                )

        finally:
            # Always attempt to restore original bola defense state on every exit path
            try:
                restore_res = client.patch(
                    f"{base_url}/admin/defenses",
                    json={"bola": original_bola},
                    headers=admin_headers,
                )
                restored_val = (
                    restore_res.json().get("defenses", {}).get("bola")
                    if restore_res.status_code == 200
                    else None
                )
                if (
                    restore_res.status_code != 200
                    or restored_val != original_bola
                ):
                    print(
                        f"[WARNING] Failed to restore original bola defense state "
                        f"(HTTP {restore_res.status_code}, "
                        f"bola={restored_val}, "
                        f"expected={original_bola}). "
                        "The server's BOLA defense state may be unresolved.",
                        file=sys.stderr,
                    )
                else:
                    restoration_succeeded = True
            except Exception as restore_exc:
                print(
                    f"[WARNING] Exception during bola defense state restoration: "
                    f"{restore_exc}. "
                    "The server's BOLA defense state may be unresolved.",
                    file=sys.stderr,
                )

        # Write combined dual-run results only after full verification and confirmed restoration
        # (no tokens, credentials, or sensitive data stored)
        if not restoration_succeeded:
            raise RuntimeError(
                "Original bola defense state was not confirmed as restored. "
                "Combined results file not written to protect experiment integrity."
            )

        combined = {
            "experiment": "OWASP API1:2023 BOLA",
            "timestamp": result_on["timestamp"],
            "target": result_on["target"],
            "attacker": "alice",
            "target_object_id": result_on["target_object_id"],
            "vulnerable_run": {
                "defense_active": result_off["defense_active"],
                "status_code": result_off["status_code"],
                "attack_success": result_off["attack_success"],
                "blocked": result_off["blocked"],
                "detection_verified": result_off["detection_verified"],
                "matched_event_id": result_off["matched_event_id"],
                "outcome": result_off["outcome"],
            },
            "defended_run": {
                "defense_active": result_on["defense_active"],
                "status_code": result_on["status_code"],
                "attack_success": result_on["attack_success"],
                "blocked": result_on["blocked"],
                "detection_verified": result_on["detection_verified"],
                "matched_event_id": result_on["matched_event_id"],
                "outcome": result_on["outcome"],
            },
        }

        if target_results_path is not False:
            assert isinstance(target_results_path, Path)
            target_results_path.parent.mkdir(parents=True, exist_ok=True)
            target_results_path.write_text(
                json.dumps(combined, indent=2), encoding="utf-8"
            )
            print(f" Results written to: {target_results_path}")

        print("\n--- Experiment Summary ---")
        print(
            f" [Vulnerable] HTTP {result_off['status_code']} | "
            f"{result_off['outcome']} | detection_verified={result_off['detection_verified']}"
        )
        print(
            f" [Defended]   HTTP {result_on['status_code']} | "
            f"{result_on['outcome']} | detection_verified={result_on['detection_verified']}"
        )
        print("==================================================")
    except Exception as exc:
        print(f"[ERROR] Experiment failed: {exc}", file=sys.stderr)
        if raise_on_failure:
            raise
        sys.exit(1)
    finally:
        if close_client:
            client.close()


if __name__ == "__main__":
    main()
